def league(league_id: str) -> FollowLeague | None:
    return next((lg for lg in FOLLOW_LEAGUES if lg.league_id == str(league_id)), None)


def teams(league_id: str) -> tuple[Team, ...]:
    return tuple(Team(tid, name) for tid, name in _TEAMS.get(str(league_id), ()))


def team_name(league_id: str, team_id: str) -> str:
    return next((name for tid, name in _TEAMS.get(str(league_id), ()) if tid == str(team_id)), "")


